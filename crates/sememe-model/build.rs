//! Build the exported model from the committed text program in `program/`:
//! the ontology becomes Rust types (so the compiler checks the type
//! hierarchy), and everything large (lexicon, counts, facts) becomes a
//! binary blob the runtime loads with `include_bytes!`.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

use sememe_engine::program::{Program, ProgramFiles};
use sememe_engine::term::TermNames;

const FILES: [&str; 5] = [
    "ontology.sem",
    "grammar.sem",
    "lexicon.sem",
    "knowledge.sem",
    "counts.tsv",
];

fn rust_ident(name: &str) -> String {
    let mut s: String = name
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '_')
        .collect();
    if s.is_empty() || s.starts_with(|c: char| c.is_ascii_digit()) {
        s.insert(0, 'C');
    }
    if s == "Self" {
        s.push('_');
    }
    s
}

fn doc(out: &mut String, text: &str, indent: &str) {
    for line in text.lines() {
        let _ = writeln!(out, "{indent}/// {line}");
    }
    if text.trim().is_empty() {
        let _ = writeln!(out, "{indent}/// (not yet documented)");
    }
}

fn main() {
    let dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default())
        .join("../../program");
    let mut files = ProgramFiles::new();
    let mut blob: Vec<u8> = Vec::new();
    for name in FILES {
        let path = dir.join(name);
        println!("cargo:rerun-if-changed={}", path.display());
        let text = std::fs::read_to_string(&path).unwrap_or_default();
        blob.extend((name.len() as u32).to_le_bytes());
        blob.extend(name.as_bytes());
        blob.extend((text.len() as u64).to_le_bytes());
        blob.extend(text.as_bytes());
        files.insert(name.to_string(), text);
    }
    let program = Program::from_files(&files).unwrap_or_else(|e| {
        println!("cargo:warning=program/ does not parse ({e}); using the seed program");
        Program::seed()
    });
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_default());
    std::fs::write(out.join("program.bin"), &blob).unwrap_or_default();

    // The ontology as Rust types.
    let mut children: BTreeMap<u32, Vec<u32>> = BTreeMap::new();
    for (id, c) in &program.concepts {
        if *id != c.parent {
            children.entry(c.parent).or_default().push(*id);
        }
    }
    let mut code =
        String::from("// Generated by build.rs from program/ontology.sem. Do not edit.\n\n");
    for (id, c) in &program.concepts {
        let name = rust_ident(&c.name);
        doc(&mut code, &c.meta.doc, "");
        let _ = writeln!(
            code,
            "///\n/// Concept `{}` (`c{id}`), added in round {}.",
            c.name, c.meta.round
        );
        match children.get(id) {
            Some(kids) => {
                let _ = writeln!(
                    code,
                    "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub enum {name} {{"
                );
                let _ = writeln!(
                    code,
                    "    /// An instance of `{name}` itself, not of a more specific concept.\n    It,"
                );
                for k in kids {
                    let kn = rust_ident(&program.concept_name(*k));
                    let _ = writeln!(code, "    /// A [`{kn}`].\n    {kn}({kn}),");
                }
                let _ = writeln!(code, "}}\n");
                for k in kids {
                    let kn = rust_ident(&program.concept_name(*k));
                    let _ = writeln!(
                        code,
                        "impl From<{kn}> for {name} {{\n    fn from(x: {kn}) -> Self {{\n        {name}::{kn}(x)\n    }}\n}}\n"
                    );
                }
            }
            None => {
                let _ = writeln!(
                    code,
                    "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub struct {name};\n"
                );
            }
        }
        let _ = writeln!(
            code,
            "impl crate::Concept for {name} {{\n    const ID: u32 = {id};\n    const NAME: &'static str = {:?};\n}}\n",
            c.name
        );
    }
    code.push_str("/// The roles a meaning node's children can fill.\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub enum Role {\n");
    for r in program.roles.values() {
        doc(&mut code, &r.meta.doc, "    ");
        let _ = writeln!(
            code,
            "    /// From `{}` to `{}`.\n    {},",
            program.concept_name(r.domain),
            program.concept_name(r.range),
            rust_ident(&upper(&r.name))
        );
    }
    code.push_str("}\n\n");
    for f in program.feats.values() {
        doc(&mut code, &f.meta.doc, "");
        let _ = writeln!(
            code,
            "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub enum {} {{",
            rust_ident(&upper(&f.name))
        );
        for v in &f.values {
            let _ = writeln!(
                code,
                "    /// `{}={v}`.\n    {},",
                f.name,
                rust_ident(&upper(v))
            );
        }
        code.push_str("}\n\n");
    }
    std::fs::write(out.join("ontology.rs"), code).unwrap_or_default();
}

fn upper(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_uppercase().chain(c).collect(),
        None => String::new(),
    }
}
